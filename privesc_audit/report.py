"""Render findings as console text, JSON, or Markdown."""

from __future__ import annotations

import json
import html
from collections import Counter
from typing import List

from .models import Finding, Severity

_COLORS = {
    Severity.CRITICAL: "\033[1;37;41m",
    Severity.HIGH: "\033[1;31m",
    Severity.MEDIUM: "\033[1;33m",
    Severity.LOW: "\033[1;36m",
    Severity.INFO: "\033[0;37m",
}
_RESET = "\033[0m"


def summary(findings: List[Finding]) -> Counter:
    return Counter(f.severity.label for f in findings)


def render_console(findings: List[Finding], use_color: bool = True) -> str:
    def c(sev, text):
        return f"{_COLORS[sev]}{text}{_RESET}" if use_color else text

    lines = ["privesc-audit — local privilege-escalation audit", "=" * 52, ""]
    if not findings:
        lines.append("No privilege-escalation findings. (Still verify manually.)")
        return "\n".join(lines)

    counts = summary(findings)
    order = [Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW, Severity.INFO]
    lines.append("Summary: " + "  ".join(
        c(s, f"{s.label}={counts.get(s.label, 0)}") for s in order if counts.get(s.label, 0)
    ))
    lines.append("")

    for f in findings:
        lines.append(c(f.severity, f"[{f.severity.label.upper()}] {f.title}"))
        lines.append(f"    {f.detail}")
        if f.evidence:
            lines.append(f"    evidence : {f.evidence}")
        lines.append(f"    fix      : {f.remediation}")
        if f.mitre:
            lines.append(f"    att&ck   : {', '.join(f.mitre)}")
        lines.append("")
    return "\n".join(lines)


def render_json(findings: List[Finding]) -> str:
    return json.dumps(
        {"summary": dict(summary(findings)), "findings": [f.to_dict() for f in findings]},
        indent=2,
    )


def render_fix_script(findings: List[Finding]) -> str:
    """Emit a reviewable shell script of the concrete hardening commands.

    Only findings with a safe, concrete ``fix_command`` are included. The script
    is meant to be *read line by line* and run by an administrator — never piped
    blindly into a shell.
    """
    fixable = [f for f in findings if f.fix_command]
    out = [
        "#!/usr/bin/env bash",
        "#",
        "# Hardening commands generated by privesc-audit.",
        "# !! REVIEW EVERY LINE before running. Run as root, on a system you are",
        "#    authorized to change. Some items (e.g. required SUID binaries) are",
        "#    intentionally omitted because auto-fixing them could break the host.",
        "#",
        "set -u",
        "",
    ]
    if not fixable:
        out.append("# No auto-fixable findings. Review the full report for manual items.")
        return "\n".join(out)
    for f in fixable:
        out.append(f"# [{f.severity.label.upper()}] {f.title}")
        out.append(f.fix_command)
        out.append("")
    out.append(f"# {len(findings) - len(fixable)} finding(s) need manual review — see the full report.")
    return "\n".join(out)


def _color_for_label(label: str):
    try:
        return _COLORS[Severity[label.upper()]]
    except (KeyError, AttributeError):
        return _COLORS[Severity.INFO]


def render_diff_console(diff, use_color: bool = True) -> str:
    """Render a baseline diff: only what is new, changed, or resolved."""
    def c(label, text):
        return f"{_color_for_label(label)}{text}{_RESET}" if use_color else text

    base_count = diff.unchanged + len(diff.changed) + len(diff.resolved)
    created = (diff.baseline_meta or {}).get("created") or "unknown date"
    lines = [
        "privesc-audit — baseline diff",
        "=" * 52,
        "",
        f"Baseline : {created}  ({base_count} findings)",
        f"Current  : {diff.current_count} findings",
        "",
    ]

    if not diff.added and not diff.changed and not diff.resolved:
        lines.append("No changes since baseline. The host's exposure is unchanged.")
        return "\n".join(lines)

    if diff.added:
        lines.append(f"NEW ({len(diff.added)}) — appeared since the baseline:")
        for f in diff.added:
            lines.append("  " + c(f.severity.label, f"[{f.severity.label.upper()}] {f.title}"))
            lines.append(f"      {f.remediation}")
            if f.mitre:
                lines.append(f"      att&ck: {', '.join(f.mitre)}")
        lines.append("")

    if diff.changed:
        lines.append(f"CHANGED severity ({len(diff.changed)}):")
        for f, old in diff.changed:
            lines.append("  " + c(f.severity.label, f"[{old.upper()} → {f.severity.label.upper()}] {f.title}"))
        lines.append("")

    if diff.resolved:
        lines.append(f"RESOLVED ({len(diff.resolved)}) — in the baseline, gone now:")
        for item in diff.resolved:
            sev = str(item.get("severity", "?"))
            lines.append("  " + c(sev, f"[was {sev.upper()}] {item.get('title', '(untitled)')}"))
        lines.append("")

    if diff.has_regression:
        lines.append("VERDICT: regression — new or worsened privilege-escalation exposure.")
    else:
        lines.append("VERDICT: no new exposure (only resolved/unchanged).")
    return "\n".join(lines)


def render_diff_json(diff) -> str:
    changed = [{**f.to_dict(), "previous_severity": old} for f, old in diff.changed]
    doc = {
        "baseline": diff.baseline_meta or {},
        "current_count": diff.current_count,
        "regression": diff.has_regression,
        "added": [f.to_dict() for f in diff.added],
        "changed": changed,
        "resolved": diff.resolved,
        "unchanged": diff.unchanged,
    }
    return json.dumps(doc, indent=2)


def render_diff_markdown(diff) -> str:
    """Render a shareable baseline diff without terminal escape sequences."""
    def cell(value):
        text = html.escape(str(value) if value is not None else "", quote=False)
        for char in "\\`*_{}[]()#+-.!|":
            text = text.replace(char, "\\" + char)
        return text.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "<br>")

    base_count = diff.unchanged + len(diff.changed) + len(diff.resolved)
    created = (diff.baseline_meta or {}).get("created") or "unknown date"
    out = [
        "# privesc-audit baseline diff", "",
        f"**Baseline:** {cell(created)} ({base_count} findings)", "",
        f"**Current:** {diff.current_count} findings", "",
        f"**Summary:** New: {len(diff.added)} · Changed: {len(diff.changed)} · "
        f"Resolved: {len(diff.resolved)} · Unchanged: {diff.unchanged}", "",
    ]
    if not diff.added and not diff.changed and not diff.resolved:
        out += ["No changes since baseline. The host's exposure is unchanged.", ""]

    sections = [
        ("New", [(f.to_dict(), f.severity.label) for f in diff.added]),
        ("Changed severity", [(f.to_dict(), f"{old} → {f.severity.label}")
                              for f, old in diff.changed]),
        ("Resolved", [(item, item.get("severity", "?")) for item in diff.resolved]),
    ]
    for title, rows in sections:
        if not rows:
            continue
        out += [f"## {title} ({len(rows)})", "",
                "| Severity | Finding | Evidence | Remediation | ATT&CK |",
                "|---|---|---|---|---|"]
        for item, severity in rows:
            values = [severity, item.get("title", "(untitled)"), item.get("evidence"),
                      item.get("remediation", ""), ", ".join(item.get("mitre") or [])]
            out.append("| " + " | ".join(cell(value) for value in values) + " |")
        out.append("")

    verdict = ("regression — new or worsened privilege-escalation exposure."
               if diff.has_regression else "no new exposure.")
    out.append(f"**VERDICT:** {verdict}")
    return "\n".join(out)


def render_markdown(findings: List[Finding]) -> str:
    out = ["# privesc-audit report", ""]
    counts = summary(findings)
    if counts:
        out.append("**Summary:** " + " · ".join(f"{k}: {v}" for k, v in counts.items()))
        out.append("")
    if not findings:
        out.append("_No privilege-escalation findings._")
        return "\n".join(out)
    out += ["| Severity | Finding | Fix |", "|---|---|---|"]
    for f in findings:
        fix = f.remediation.replace("|", "\\|")
        title = f.title.replace("|", "\\|")
        out.append(f"| {f.severity.label} | {title} | {fix} |")
    return "\n".join(out)
